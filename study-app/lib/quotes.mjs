/** 固定种子的伪随机，保证每次启动洗出来的顺序完全一样 */
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher–Yates，用固定种子 */
function shuffle(list, seed) {
  const rand = mulberry32(seed);
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** 洗完之后再走一遍：尽量不让连着两天出自同一本书 */
function declump(list) {
  const out = list.slice();
  for (let i = 1; i < out.length; i += 1) {
    if (out[i].from !== out[i - 1].from) continue;
    const j = out.findIndex((q, k) => k > i && q.from !== out[i - 1].from);
    if (j > i) [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** 每日轮换的真正顺序（已打乱） */
export const ORDER = declump(shuffle(RAW, 20271218));

/** 内置句子（已打乱顺序） */
export const QUOTES = ORDER;

/**
 * 距离 1970-01-01 的天数（按本地日算）
 * @param {string} dateStr YYYY-MM-DD
 */
export function dayIndex(dateStr) {
  const [y, m, d] = String(dateStr).slice(0, 10).split('-').map(Number);
  if (!y || !m || !d) return 0;
  return Math.round((new Date(y, m - 1, d) - new Date(1970, 0, 1)) / 86400000);
}

/**
 * 取某一天的句子：同一天永远同一句，跨天自动换一句。
 * @param {string} dateStr YYYY-MM-DD
 * @param {Array<{text:string, from:string}>} [extra] 用户自己加的句子（排在内置之后）
 */
export function quoteOfTheDay(dateStr, extra = []) {
  const list = extra.length ? [...QUOTES, ...extra] : QUOTES;
  if (!list.length) return null;
  const n = list.length;
  const index = ((dayIndex(dateStr) % n) + n) % n;
  const q = list[index];
  return { text: q.text, from: q.from, index, total: n, date: String(dateStr).slice(0, 10) };
}

/**
 * 读用户自己加的句子：一行一句，`句子 | 出处`（出处可省）。
 * 文件不存在就返回空数组，不影响内置句子。
 */
export function parseExtraQuotes(raw) {
  return String(raw || '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const i = line.lastIndexOf('|');
      if (i < 0) return { text: line, from: '自己加的' };
      return { text: line.slice(0, i).trim(), from: line.slice(i + 1).trim() || '自己加的' };
    })
    .filter((q) => q.text);
}

const src = fs.readFileSync(FILE, 'utf8');
const lines = src.split('\n');
const dropSet = new Set(DROP);
const hit = new Set();
const dropLines = new Set();

lines.forEach((line, i) => {
  const m = /^\s*'(.*)',?\s*$/.exec(line);
  if (!m) return;
  const text = m[1];
  if (!dropSet.has(text)) return;
  hit.add(text);
  if (dropLines.has(text)) return;
  dropLines.add(i);
});

const missed = DROP.filter((t) => !hit.has(t));
const dupInDrop = DROP.filter((t, i) => DROP.indexOf(t) !== i);
console.log(`要删 ${DROP.length} 条（去重后 ${dropSet.size}）· 命中 ${hit.size} 行`);
if (missed.length) console.log('⚠️ 没找到：', missed);
if (dupInDrop.length) console.log('⚠️ 清单里有重复：', dupInDrop);

const out = lines.filter((_, i) => !dropLines.has(i)).join('\n');

if (process.argv.includes('--write')) {
  fs.writeFileSync(FILE, out);
  console.log(`已写回 ${FILE}`);
} else {
  console.log('（预览模式，加 --write 才真删）');
}
